#!/usr/bin/env node
// Regenerates extension/config.js with a default Job Tracker URL, so
// installing the extension "just works" against your own instance without
// you having to type its URL into the Options page yourself — the Options
// page becomes an override for the rare case you actually want a different
// target, not a required first step.
//
// The source of truth is the exact same `NEXT_PUBLIC_APP_URL` the app
// itself is built with (see docker-compose.yml's build-arg comment) — every
// self-hoster already has to set this to build the app, so this adds zero
// new configuration. Run automatically via the `predev`/`prebuild` npm
// lifecycle hooks (see package.json); `pnpm ext:build`/`ext:sign` run it too
// so a packaged extension bakes in whatever URL was current at build time.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "extension", "config.js");

// `next dev`/`next build` load `.env.local` themselves; a plain `node`
// script run from an npm lifecycle hook doesn't get that for free, so read
// it directly here for the common local-dev case. Production builds (e.g.
// the Dockerfile) already set NEXT_PUBLIC_APP_URL as a real env var before
// `pnpm build` runs, so this is purely a local-dev convenience — an
// existing `process.env` value always wins.
function loadDotEnvLocal() {
  const envFile = path.join(root, ".env.local");
  if (!existsSync(envFile)) return;
  for (const line of readFileSync(envFile, "utf8").split("\n")) {
    const match = /^\s*([\w.-]+)\s*=\s*(.*)\s*$/.exec(line);
    if (!match) continue;
    const [, key, rawValue] = match;
    if (process.env[key] !== undefined) continue;
    process.env[key] = rawValue.replace(/^["']|["']$/g, "");
  }
}
loadDotEnvLocal();

const url = process.env.NEXT_PUBLIC_APP_URL?.replace(/\/+$/, "");

const contents = url
  ? `// Generated by \`pnpm ext:configure\` (scripts/generate-extension-config.mjs)
// from NEXT_PUBLIC_APP_URL — do not edit by hand. Committed with a null
// default (see below) so a fresh checkout's manifest.json always has a real
// file to load; \`pnpm dev\`/\`pnpm build\`/\`pnpm ext:*\` regenerate it with
// your actual instance's URL as an uncommitted local change, the same
// pattern this repo already uses for AGENTS.md (see AGENTS.md itself).
self.JOB_TRACKER_DEFAULT_APP_URL = ${JSON.stringify(url)};
`
  : `// Generated by \`pnpm ext:configure\` (scripts/generate-extension-config.mjs) —
// NEXT_PUBLIC_APP_URL wasn't set, so no default could be baked in. The
// extension falls back to asking for the URL in its Options page.
self.JOB_TRACKER_DEFAULT_APP_URL = null;
`;

writeFileSync(outFile, contents);
console.log(`extension/config.js -> ${url ?? "(no default; NEXT_PUBLIC_APP_URL unset)"}`);
